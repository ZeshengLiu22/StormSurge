#!/usr/bin/env python3
"""Inspect inputs, then generate the complete fixed matrix without submitting jobs."""
import argparse
import json
from pathlib import Path
import shlex

from common import (CKPT_ROOT, DATA_ROOT, LAUNCHER, REPO, RESULT_ROOT, RESOURCES,
                    SOURCES, STATIONS, MODELS, YEARS, DEFAULT_RUNTIME, PYTHON,
                    atomic_json, combinations, graph_inventory, identity,
                    inspect_checkpoint, memory_estimate, require, resolve_checkpoint)


def config_text(row, manifest):
    values = dict(MANIFEST=str(manifest), RUN_ID=row['id'], CMIP6=row['source'], STATION=row['station'],
                  SEED=str(row['seed']), MODEL_LABEL=row['model'], MODEL=row['model_key'],
                  CKPT=row['checkpoint'], ROOT_DIR=row['source_root'], TEST_ROOT_DIR=row['test_root_dir'],
                  OUT_DIR=row['output_dir'] + '/outputs', YEARS=','.join(YEARS), STRICT_YEARS='1', SAVE_NPZ='1')
    return '#!/usr/bin/env bash\n# Generated assignment-only config; station_runner.py consumes the pinned manifest.\n' + ''.join(
        f'{key}={shlex.quote(value)}\n' for key, value in values.items())


def pbs_text(cluster, source, station, launcher, walltime):
    directory = launcher / cluster / source
    if station:
        directory /= station
    job = 'fi' + ('D' if cluster == 'derecho' else 'C') + str(SOURCES.index(source))
    if station:
        job += str(STATIONS.index(station))
    queue = 'preempt@desched1' if cluster == 'derecho' else 'casper'
    args = [cluster, source] + ([station] if station else [])
    return f'''#!/usr/bin/env bash
# Generated by generate.py; override walltime using qsub -l walltime=HH:MM:SS.
#PBS -N {job}
#PBS -A ULHI0005
#PBS -q {queue}
#PBS -l {RESOURCES[cluster]}
#PBS -l walltime={walltime}
#PBS -r n
#PBS -j oe
#PBS -o {directory}/pbs_logs/
set -euo pipefail
exec bash {shlex.quote(str(launcher / 'run_job.sh'))} {shlex.join(args)}
'''


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo', type=Path, default=REPO)
    parser.add_argument('--checkpoint-root', type=Path, default=CKPT_ROOT)
    parser.add_argument('--data-root', type=Path, default=DATA_ROOT)
    parser.add_argument('--result-root', type=Path, default=RESULT_ROOT)
    parser.add_argument('--selection', type=Path, help='JSON mapping source/station/seed/model to an exact checkpoint')
    parser.add_argument('--reuse-manifest', type=Path, help='Explicitly retain the checkpoints pinned by this earlier manifest')
    parser.add_argument('--derecho-walltime', default='01:00:00')
    parser.add_argument('--casper-walltime', default='02:00:00')
    args = parser.parse_args(argv)
    import re
    for value in (args.derecho_walltime, args.casper_walltime):
        require(re.fullmatch(r'\d{2,3}:[0-5]\d:[0-5]\d', value), 'Invalid walltime')
    launcher = args.repo.absolute() / 'PBS-launcher/cmip6_inference'
    manifest_path = launcher / 'manifest.json'
    selections = {}
    if args.reuse_manifest:
        selections.update({row['id']: row['checkpoint'] for row in json.loads(args.reuse_manifest.read_text())['runs']})
    if args.selection:
        selections.update(json.loads(args.selection.read_text()))
    expected = {identity(*item) for item in combinations()}
    require(set(selections) <= expected, 'Unknown combination in checkpoint selection')
    inventories, memory = {}, {}
    for source in SOURCES:
        for station in STATIONS:
            key = source + '/' + station
            inventory = graph_inventory(args.data_root / source / 'graphs', station)
            inventories[key] = inventory
            memory[key] = memory_estimate(inventory)
            require(memory[key] < 240 * 0.8, f'{key}: estimated CPU memory exceeds Casper safety budget')
        require(sum(memory[source + '/' + s] for s in STATIONS) < 487 * 0.8,
                f'{source}: estimated four-station memory exceeds Derecho safety budget')
    runs = []
    errors = []
    for source, station, seed, model in combinations():
        key = identity(source, station, seed, model)
        try:
            checkpoint = resolve_checkpoint(args.checkpoint_root, source, station, seed, model, selections)
            metadata = inspect_checkpoint(checkpoint, source, station, seed, model)
            row = dict(id=key, source=source, station=station, seed=seed, model=model, model_key=MODELS[model],
                       checkpoint=str(checkpoint), checkpoint_metadata=metadata,
                       source_root=metadata['source_root'],
                       test_root_dir=str((args.data_root / source / 'graphs').absolute()),
                       output_dir=str((args.result_root / key).absolute()),
                       config=str((args.repo / 'configs/cmip6_inference' / source / station / f'seed{seed}' / f'infer_config_{model}.sh').absolute()),
                       derecho_pbs=str(launcher / 'derecho' / source / 'run_inference.pbs'),
                       casper_pbs=str(launcher / 'casper' / source / station / 'run_inference.pbs'))
            runs.append(row)
        except Exception as error:
            errors.append(f'{key}: {error}')
        if (len(runs) + len(errors)) % 48 == 0:
            print(f'Inspected {len(runs) + len(errors)}/432 checkpoints', flush=True)
    require(not errors, 'No matrix written; fix checkpoint errors:\n' + '\n'.join(errors))
    require(len({row['output_dir'] for row in runs}) == 432, 'Duplicate output destination')
    manifest = dict(schema_version=1, years=YEARS, sources=list(SOURCES), stations=list(STATIONS),
                    python=PYTHON, runtime_defaults=DEFAULT_RUNTIME, repo=str(args.repo.absolute()),
                    checkpoint_root=str(args.checkpoint_root.absolute()), data_root=str(args.data_root.absolute()),
                    result_root=str(args.result_root.absolute()), graph_inventory=inventories,
                    memory_estimate_gib=memory,
                    walltimes=dict(derecho=args.derecho_walltime, casper=args.casper_walltime), runs=runs)
    # Validate everything before publishing any generated files. Per-file writes are atomic.
    launcher.mkdir(parents=True, exist_ok=True)
    for row in runs:
        path = Path(row['config'])
        path.parent.mkdir(parents=True, exist_ok=True)
        temp = path.with_suffix('.tmp')
        temp.write_text(config_text(row, manifest_path))
        temp.replace(path)
        Path(row['output_dir']).mkdir(parents=True, exist_ok=True)
    for cluster in RESOURCES:
        for source in SOURCES:
            for station in (STATIONS if cluster == 'casper' else (None,)):
                directory = launcher / cluster / source
                if station:
                    directory /= station
                (directory / 'pbs_logs').mkdir(parents=True, exist_ok=True)
                path = directory / 'run_inference.pbs'
                temp = path.with_suffix('.tmp')
                temp.write_text(pbs_text(cluster, source, station, launcher, manifest['walltimes'][cluster]))
                temp.replace(path)
    atomic_json(manifest_path, manifest)
    print(f'Generated 432 configs, 432 result locations, 9 Derecho PBS, 36 Casper PBS; {manifest_path}')


if __name__ == '__main__':
    main()
